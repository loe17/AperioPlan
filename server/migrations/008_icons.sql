  where p.icon !~ '^[a-z][a-z0-9-]*(:#[0-9a-fA-F]{3,8})?$';
update teams t set icon = coalesce((select name from _icon_map where emoji in (t.icon, replace(t.icon, U&'\FE0F', '')) limit 1), 'team')
  where t.icon !~ '^[a-z][a-z0-9-]*(:#[0-9a-fA-F]{3,8})?$';

alter table projects alter column icon set default 'rocket';
alter table teams alter column icon set default 'team';
